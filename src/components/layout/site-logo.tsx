/** 标记的坐标系（100×100），顶栏与标签页图标共用 */
export const SITE_LOGO_VIEW_BOX = "0 0 100 100";

/**
 * 站点标记：手画的「wk」连写（文凯的首字母）。
 *
 * 一笔到底，重点是 **k 的笔顺**：入笔 → w 的两个谷 → 从第二个谷底上挑到顶 → 顶部一个
 * 小环 → 往回走一小段 → **手臂那条上斜线自己绕成第二个环** → 从环里出来一条长弧甩向右下
 * 收笔。
 *
 * 两个环的**位置与形状**是刻意调过的：顶部环小（蝴蝶结，约 9×11）；第二个环**窄而长**
 * （约 10 宽 × 19 高），并且**整体下移**，与顶部环之间留出约 12 单位的竖直空档 —— 那口
 * 空档就是"叶子从竖的中段才长出来"的味道；贴在一起会糊成一片，太宽则洞都看不见。
 * 与更早版本的差别都在笔顺与这两处节奏：最初把竖写了两遍（白跑一趟）；后来竖只走一遍，
 * 但上行段与回程段贴在一起叠成粗带；再后来第二个环是片大叶子，两条弧在尖上并成实心。
 *
 * - **尺寸由外部给**（`size-*` 或宽高属性都行），**颜色吃 `currentColor`**，所以
 *   日夜模式自动跟随，不必像上游那样在 CSS 里写死两套颜色；
 * - **自绘动画在 `globals.css` 的 `.site-logo path` 那条规则**里（写出来 → 停住 →
 *   擦掉，10s 循环；减少动效与打印时静态）。其中的 dasharray 常量 290 略大于这条
 *   路径的总长（按贝塞尔采样量得约 312）—— 改下面的 `d` 要连它一起改（取
 *   `path.getTotalLength()`，或采样估算，取整并留一点余量）；
 * - 路径是**手画**的（控制点按手写笔迹的节奏调过，不是算法生成）。要换字形，
 *   或者将来换成真人签名的描摹，**只替换这个 `d` 就行**，动画、尺寸、颜色都不用动。
 */
export function SiteLogo({ className, ...props }: React.ComponentProps<"svg">) {
  return (
    <svg
      // 必须用 cn() 合并：如果直接写字，调用方传进来的 className 会把它整个覆盖掉
      // （`<SiteLogo className="size-10" />` → class 只剩 size-10），动画也就不生效了
      className={cn("site-logo", className)}
      viewBox={SITE_LOGO_VIEW_BOX}
      fill="none"
      stroke="currentColor"
      strokeWidth={3}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      <path d={SITE_LOGO_PATH} />
    </svg>
  );
}
