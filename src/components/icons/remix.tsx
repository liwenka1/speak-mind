/**
 * Remix Icon 的线性图标，统一取 `-line` 变体。
 *
 * 为什么是这一套：顶栏那排图标（GitHub / 邮箱 / X / 主题）需要同样的笔画粗细，
 * Remix 一个集合里就齐了，不用东拼西凑。
 *
 * 为什么把路径内置、而不是装图标库：这里只用得到 6 个图标，而 `@iconify/react`
 * 这类方案会把整套 Remix（上千个图标）带进构建；内置更接近本项目既有的
 * "vendored 一个上游文件" 路子（见 components/ui/empty.tsx、app/typeset.css）。
 *
 * - 来源：https://api.iconify.design/ri.json?icons=github-line,mail-line,twitter-x-line,sun-line,moon-line,link
 *   要加/换图标就重跑这条 API，把新的 `d` 换进来即可。
 * - 集合：Remix Icon（Apache-2.0，作者 Remix Design）。
 * - 这些图标是**填充**式的：线条本身就是实心形状、颜色吃 `currentColor`，
 *   所以别给它们加 `stroke-*` 类（lucide 那套才是 stroke）。
 * - 尺寸默认 1em，用 `size-*` 类覆盖（顶栏统一 16px）。
 */
type IconProps = React.ComponentProps<"svg">;

/** 6 个图标的外壳都一样：24×24 方形、填充、颜色跟随文字 */
